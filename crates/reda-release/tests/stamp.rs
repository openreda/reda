use reda_release::{Version, stamp_lock, stamp_manifest};

fn v(text: &str) -> Version {
    text.parse().unwrap()
}

#[test]
fn stamps_the_workspace_package_version_and_nothing_else() {
    let manifest = r#"[workspace]
members = ["crates/*"]

[workspace.package]
version = "0.0.0" # stamped by CI
edition = "2024"

[workspace.dependencies]
serde = { version = "1.0.228", features = ["derive"] }
toml_edit = "0.25"
"#;
    let expected = r#"[workspace]
members = ["crates/*"]

[workspace.package]
version = "0.3.7" # stamped by CI
edition = "2024"

[workspace.dependencies]
serde = { version = "1.0.228", features = ["derive"] }
toml_edit = "0.25"
"#;
    assert_eq!(stamp_manifest(manifest, v("0.3.7")).unwrap(), expected);
}

#[test]
fn a_manifest_without_a_workspace_version_is_an_error() {
    let err = stamp_manifest("[workspace]\nmembers = []\n", v("0.1.0")).unwrap_err();
    assert!(err.contains("workspace.package"), "{err}");
}

#[test]
fn stamping_this_workspace_changes_exactly_the_reda_crate_versions() {
    let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../..");
    let manifest = std::fs::read_to_string(format!("{root}/Cargo.toml")).unwrap();
    let lock = std::fs::read_to_string(format!("{root}/Cargo.lock")).unwrap();

    let stamped = stamp_manifest(&manifest, v("9.8.7")).unwrap();
    let changed: Vec<_> = diff_lines(&manifest, &stamped);
    assert_eq!(changed, ["version = \"9.8.7\""]);

    let stamped = stamp_lock(&lock, v("9.8.7")).unwrap();
    let crates = std::fs::read_dir(format!("{root}/crates")).unwrap().count();
    let changed = diff_lines(&lock, &stamped);
    assert_eq!(
        changed.len(),
        crates,
        "one version line per workspace crate"
    );
    assert!(changed.iter().all(|line| *line == "version = \"9.8.7\""));
}

/// The lines of `after` that differ from the same line of `before`.
fn diff_lines<'a>(before: &str, after: &'a str) -> Vec<&'a str> {
    assert_eq!(before.lines().count(), after.lines().count());
    before
        .lines()
        .zip(after.lines())
        .filter(|(b, a)| b != a)
        .map(|(_, a)| a)
        .collect()
}

#[test]
fn stamps_the_workspace_crates_in_the_lockfile_and_leaves_registry_crates() {
    let lock = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "reda-cli"
version = "0.0.0"
dependencies = [
 "reda-engine",
 "serde",
]

[[package]]
name = "reda-engine"
version = "0.0.0"

[[package]]
name = "serde"
version = "1.0.228"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "9a8e94ea7f378bd32cbbd37198a4a91436180c5bb472411e48b5ec2e2124ae9e"
"#;
    let expected = lock
        .replacen("version = \"0.0.0\"", "version = \"1.2.3\"", 2)
        .to_owned();
    assert_eq!(stamp_lock(lock, v("1.2.3")).unwrap(), expected);
}
