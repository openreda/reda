//! The placeholder icon vendoring: reading the sources list, rewriting the SVGs, and the
//! generated table and README.

use reda_xtask::icons::{IconSet, Source, parse_sources, readme, table_rs, vendor_svg};

#[test]
fn sources_list_one_icon_per_key_and_skip_comments() {
    let text = "# comment\n\nsave lucide:save\nwire  tabler:line\n";
    let sources = parse_sources(text).unwrap();
    assert_eq!(
        sources,
        vec![
            Source {
                key: "save".into(),
                set: IconSet::Lucide,
                name: "save".into()
            },
            Source {
                key: "wire".into(),
                set: IconSet::Tabler,
                name: "line".into()
            },
        ]
    );
}

#[test]
fn sources_list_refuses_unknown_sets_bad_keys_and_repeats() {
    let unknown = parse_sources("save feather:save\n").unwrap_err();
    assert!(unknown.contains("line 1"), "{unknown}");
    assert!(parse_sources("Save lucide:save\n").is_err());
    assert!(parse_sources("save lucide\n").is_err());
    let twice = parse_sources("save lucide:save\nsave tabler:device-floppy\n").unwrap_err();
    assert!(twice.contains("save"), "{twice}");
}

#[test]
fn vendored_svgs_are_drawn_white_without_licence_comments_or_classes() {
    let lucide = "<!-- @license lucide-static v1.66.0 - ISC -->\n<svg\n  class=\"lucide lucide-save\"\n  xmlns=\"http://www.w3.org/2000/svg\"\n  stroke=\"currentColor\"\n>\n  <path d=\"M1 1\" />\n</svg>\n";
    assert_eq!(
        vendor_svg(lucide),
        "<svg\n  xmlns=\"http://www.w3.org/2000/svg\"\n  stroke=\"#fff\"\n>\n  <path d=\"M1 1\" />\n</svg>\n"
    );
    let filled = "<svg fill=\"currentColor\"><path stroke=\"none\" d=\"M0 0h24v24H0z\" fill=\"none\" /></svg>";
    assert_eq!(
        vendor_svg(filled),
        "<svg fill=\"#fff\"><path stroke=\"none\" d=\"M0 0h24v24H0z\" fill=\"none\" /></svg>\n"
    );
}

#[test]
fn table_includes_every_key_in_order() {
    let table = table_rs(&["save".into(), "wire".into()]);
    assert!(table.starts_with("// @generated by `cargo xtask icons`"));
    let save = table.find("(\"save\", egui::include_image!(\"../../icons/save.svg\"))");
    let wire = table.find("(\"wire\", egui::include_image!(\"../../icons/wire.svg\"))");
    assert!(save.is_some() && wire.is_some(), "{table}");
    assert!(save < wire);
}

#[test]
fn readme_records_each_icons_provenance() {
    let sources = parse_sources("save lucide:save\nwire tabler:line\n").unwrap();
    let text = readme(&sources);
    assert!(text.contains("| `save` | Lucide `save` |"), "{text}");
    assert!(
        text.contains("| `wire` | Tabler `line` (outline) |"),
        "{text}"
    );
    assert!(text.contains("lucide-static"));
    assert!(text.contains("@tabler/icons"));
    assert!(text.contains("LICENSE-lucide.txt") && text.contains("LICENSE-tabler.txt"));
}
