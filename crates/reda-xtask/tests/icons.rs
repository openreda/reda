//! The icon tables: reading `reda.txt`, the generated table and README, and refusing a
//! listed key without its SVG.

use reda_xtask::icons::{Owned, parse_owned, readme, regenerate, table_rs};

#[test]
fn table_includes_every_key_in_order() {
    let table = table_rs(&["wire".into(), "save".into()]);
    assert!(table.starts_with("// @generated by `cargo xtask icons`"));
    let save = table.find("(\"save\", egui::include_image!(\"../../icons/save.svg\"))");
    let wire = table.find("(\"wire\", egui::include_image!(\"../../icons/wire.svg\"))");
    assert!(save.is_some() && wire.is_some(), "{table}");
    assert!(save < wire);
}

#[test]
fn icons_list_their_provenance() {
    let owned =
        parse_owned("# comment\nwire | Claude (Opus 5.5), hand-written SVG | none | none\n")
            .unwrap();
    assert_eq!(
        owned,
        vec![Owned {
            key: "wire".into(),
            drawn_by: "Claude (Opus 5.5), hand-written SVG".into(),
            reference: "none".into(),
            cleaned_up_by: "none".into(),
        }]
    );
    assert!(parse_owned("wire | only two | fields\n").is_err());
    assert!(parse_owned("Wire | a | b | c\n").is_err());
    assert!(parse_owned("wire | a | b | c\nwire | a | b | c\n").is_err());

    let text = readme(&owned);
    assert!(text.contains("REDA's own icons, MIT"), "{text}");
    assert!(text.contains("| `#2fb36b` | `#228a51` |"), "{text}");
    assert!(
        text.contains("| `wire` | Claude (Opus 5.5), hand-written SVG | none | none |"),
        "{text}"
    );
}

/// A scratch folder holding a small reda-ui: its icon list and one SVG.
fn scratch(name: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("reda-xtask-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let write = |path: &str, text: &str| {
        let path = dir.join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    };
    write("ui/src/icons/.keep", "");
    write("ui/icons/reda.txt", "wire | Claude | none | none\n");
    write("ui/icons/wire.svg", "<svg stroke=\"#2fb36b\"/>\n");
    dir
}

#[test]
fn regenerating_writes_the_table_and_readme_and_leaves_the_svgs_alone() {
    let dir = scratch("regen");
    assert_eq!(regenerate(&dir.join("ui")).unwrap(), 1);
    let icons = dir.join("ui/icons");
    let read = |f: &str| std::fs::read_to_string(icons.join(f)).unwrap();
    assert_eq!(read("wire.svg"), "<svg stroke=\"#2fb36b\"/>\n");
    let table = std::fs::read_to_string(dir.join("ui/src/icons/table.rs")).unwrap();
    assert!(table.contains("\"wire\""), "{table}");
    assert!(read("README.md").contains("| `wire` | Claude | none | none |"));
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn a_listed_key_without_an_svg_is_refused() {
    let dir = scratch("missing");
    std::fs::write(
        dir.join("ui/icons/reda.txt"),
        "wire | Claude | none | none\nsave | Claude | none | none\n",
    )
    .unwrap();
    let error = regenerate(&dir.join("ui")).unwrap_err();
    assert!(error.contains("save"), "{error}");
    assert!(!dir.join("ui/src/icons/table.rs").exists());
    std::fs::remove_dir_all(&dir).unwrap();
}
