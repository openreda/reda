//! Regenerating reda-ui's icon tables (docs/spec/v0.1/app.md#icons).
//!
//! Every semantic icon key has REDA's own art, drawn to the style guide in issue #32 and
//! listed with its provenance in `crates/reda-ui/icons/reda.txt`. `cargo xtask icons`
//! checks that each listed key has its SVG, then rewrites the README's provenance table and
//! `crates/reda-ui/src/icons/table.rs`, the key → image table.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

/// One of REDA's icons: its key and its provenance, as the style guide asks.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Owned {
    pub key: String,
    /// Who drew it: an agent model or a person.
    pub drawn_by: String,
    /// Any reference or generator it was drawn from, with its prompt.
    pub reference: String,
    /// Who cleaned it up.
    pub cleaned_up_by: String,
}

fn valid_key(key: &str) -> bool {
    !key.is_empty()
        && key
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
}

/// Reads the icon list: `<key> | <drawn by> | <reference> | <cleaned up by>` per line, `#`
/// comments and blank lines skipped. Keys are lowercase snake_case and appear once.
pub fn parse_owned(text: &str) -> Result<Vec<Owned>, String> {
    let mut owned = Vec::new();
    let mut keys = BTreeSet::new();
    for (i, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let bad = |why: &str| format!("reda.txt line {}: {why}: {line}", i + 1);
        let fields: Vec<&str> = line.split('|').map(str::trim).collect();
        let [key, drawn_by, reference, cleaned_up_by] = fields[..] else {
            return Err(bad(
                "expected `<key> | <drawn by> | <reference> | <cleaned up by>`",
            ));
        };
        if !valid_key(key) {
            return Err(bad("the key is not lowercase snake_case"));
        }
        if !keys.insert(key.to_owned()) {
            return Err(bad(&format!("the key {key} is listed twice")));
        }
        owned.push(Owned {
            key: key.to_owned(),
            drawn_by: drawn_by.to_owned(),
            reference: reference.to_owned(),
            cleaned_up_by: cleaned_up_by.to_owned(),
        });
    }
    Ok(owned)
}

/// The generated `reda-ui/src/icons/table.rs` before rustfmt: every key with its SVG,
/// sorted by key.
pub fn table_rs(keys: &[String]) -> String {
    let mut keys = keys.to_vec();
    keys.sort();
    let mut out = String::from(
        "// @generated by `cargo xtask icons` from icons/reda.txt; do not edit.\n\n\
         /// Every icon key with its SVG (dark-theme colours), sorted by key.\n\
         pub(super) const ICONS: &[(&str, egui::ImageSource<'static>)] = &[\n",
    );
    for key in keys {
        let _ = writeln!(
            out,
            "    (\"{key}\", egui::include_image!(\"../../icons/{key}.svg\")),"
        );
    }
    out.push_str("];\n");
    out
}

/// The icon set's README: the role colours and one provenance row per icon.
pub fn readme(owned: &[Owned]) -> String {
    let mut out = String::from(
        "# Icons\n\n\
         <!-- @generated by `cargo xtask icons` from reda.txt; do not edit. -->\n\n\
         REDA's own icons, MIT like the repo: one SVG per semantic icon key \
         (docs/spec/v0.1/app.md#icons), drawn to the style guide in issue #32.\n\n\
         ## Role colours\n\n\
         The icons use only these colours, written as the dark-theme value; reda-ui swaps \
         each for its light-theme value on load (`ROLES` in `src/icons.rs`). Each reaches at \
         least 3:1 on its theme's panel.\n\n\
         | Role | Dark (in file) | Light |\n|---|---|---|\n\
         | Existing / context (pins, pads, frames, the thing acted on) | `#8a93a0` | `#727984` |\n\
         | Created, schematic (Wire, Net Label, Power Port…) | `#2fb36b` | `#228a51` |\n\
         | Created, PCB copper (Track, Via, Zone, Pad…) | `#e08a2e` | `#ac6921` |\n\
         | Created, general (file, edit, view, selection, checks) | `#3d8fd6` | `#347dbc` |\n\
         | Picked point | `#ec4f7a` | `#d2456c` |\n\
         | Created, board edge and keepout (Board Outline, Board Cutout, Keepout) | `#d4c03c` | `#8a7a12` |\n\n\
         ## Provenance\n\n\
         Each icon is listed in `reda.txt`. To add one, draw `<key>.svg`, list it there and \
         run `cargo xtask icons`.\n\n\
         | Key | Drawn by | Reference | Cleaned up by |\n|---|---|---|---|\n",
    );
    for o in owned {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            o.key, o.drawn_by, o.reference, o.cleaned_up_by
        );
    }
    out
}

/// `cargo xtask icons`: checks that every key in `<ui>/icons/reda.txt` has its SVG, and
/// regenerates the README and `<ui>/src/icons/table.rs`. Returns the number of icons.
pub fn regenerate(ui: &Path) -> Result<usize, String> {
    let icons = ui.join("icons");
    let owned = parse_owned(&read(&icons.join("reda.txt"))?)?;
    for o in &owned {
        let svg = icons.join(format!("{}.svg", o.key));
        if !svg.exists() {
            return Err(format!(
                "reda.txt lists {}, which has no SVG",
                svg.display()
            ));
        }
    }
    write(&icons.join("README.md"), &readme(&owned))?;
    let keys: Vec<String> = owned.iter().map(|o| o.key.clone()).collect();
    let table = ui.join("src/icons/table.rs");
    write(&table, &table_rs(&keys))?;
    // Formatted as `cargo fmt` would, so `cargo fmt --check` passes on it.
    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(&table)
        .status()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !status.success() {
        return Err(format!("rustfmt failed: {status}"));
    }
    Ok(owned.len())
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}
