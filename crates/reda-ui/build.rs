//! Builds `THIRD_PARTY_NOTICES` into `OUT_DIR`, for Help > About > Licences
//! (docs/spec/v0.1/app.md#icons). `reda_ui::help::NOTICES` embeds it.
//!
//! - **Bundled data** comes from the hand-kept list `packaging/notices/vendored.txt`, with
//!   each entry's licence texts copied in.
//! - **Rust crates**: the release workflow generates the crate licences with cargo-about
//!   and points `REDA_CRATE_NOTICES` at that file. A release build (`REDA_RELEASE=1`) fails
//!   without it; a local build says where the list comes from instead.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let root = manifest.join("../..");
    let list_path = root.join("packaging/notices/vendored.txt");
    println!("cargo:rerun-if-changed={}", list_path.display());
    println!("cargo:rerun-if-env-changed=REDA_CRATE_NOTICES");
    println!("cargo:rerun-if-env-changed=REDA_RELEASE");

    let mut out = String::from(
        "THIRD-PARTY NOTICES\n\
         \n\
         REDA is MIT-licensed. It ships with the third-party data and Rust crates below, \
         under their own licences.\n",
    );

    out.push_str("\n\n======== Bundled data ========\n");
    let list = read(&list_path);
    for line in list.lines() {
        let line = line.trim_end();
        if line.starts_with('#') {
            continue;
        }
        if let Some(title) = line.strip_prefix("== ").and_then(|l| l.strip_suffix(" ==")) {
            write!(out, "\n\n---- {title} ----\n\n").unwrap();
        } else if let Some(file) = line.strip_prefix("Text: ") {
            let path = root.join(file);
            println!("cargo:rerun-if-changed={}", path.display());
            write!(out, "\n{file}:\n\n{}\n", read(&path).trim_end()).unwrap();
        } else if !line.is_empty() {
            assert!(
                line.contains(": "),
                "{}: expected `== Title ==`, `Key: value` or a comment, found {line:?}",
                list_path.display()
            );
            writeln!(out, "{line}").unwrap();
        }
    }

    out.push_str("\n\n======== Rust crates ========\n\n");
    match std::env::var_os("REDA_CRATE_NOTICES") {
        Some(path) => {
            let path = PathBuf::from(path);
            println!("cargo:rerun-if-changed={}", path.display());
            out.push_str(read(&path).trim());
            out.push('\n');
        }
        None => {
            assert!(
                std::env::var("REDA_RELEASE").as_deref() != Ok("1"),
                "a release build needs the crate licences: set REDA_CRATE_NOTICES to the file \
                 `cargo about generate` wrote"
            );
            out.push_str(
                "This is a local build. Release builds list every Rust crate REDA is built \
                 from here, with its licence text, generated by cargo-about.\n",
            );
        }
    }

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("set by cargo"));
    std::fs::write(out_dir.join("THIRD_PARTY_NOTICES"), out).expect("write THIRD_PARTY_NOTICES");
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()))
}
